import type { MetadataRoute } from 'next';
import { getConfig } from '@/lib/config';

// Required for static export (output: 'export')
export const dynamic = 'force-static';

/**
 * Statically generated sitemap (emitted as out/sitemap.xml on `next build`).
 * Lists the homepage plus every dynamically routed page: navigation pages,
 * [[subpages]] targets, and [legal] slugs — mirroring generateStaticParams
 * in src/app/[slug]/page.tsx. Requires site.url to be set in content/config.toml.
 */
export default function sitemap(): MetadataRoute.Sitemap {
  const config = getConfig();

  if (!config.site.url) {
    console.warn('Skipping sitemap generation: set url in [site] (content/config.toml) to enable it.');
    return [];
  }

  const base = config.site.url.replace(/\/+$/, '');
  const lastModified = new Date();

  // Pages linked from the main navigation (except the homepage, which lives
  // at "/" and is generated by src/app/page.tsx).
  const navSlugs = config.navigation
    .filter((nav) => nav.type === 'page' && nav.target !== 'about')
    .map((nav) => nav.target);

  // Additional pages not shown in the main nav menu ([[subpages]]).
  const subpageSlugs = (config.subpages || []).map((page) => page.target);

  // Legal pages linked from the footer ([legal] section).
  const legalSlugs = [config.legal?.imprint, config.legal?.privacy].filter(
    (slug): slug is string => Boolean(slug)
  );

  const slugs = Array.from(new Set([...navSlugs, ...subpageSlugs, ...legalSlugs]));

  return [
    { url: `${base}/`, lastModified },
    ...slugs.map((slug) => ({
      url: `${base}/${slug}/`,
      lastModified,
    })),
  ];
}
