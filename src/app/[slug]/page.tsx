/**
 * Load a BibTeX source and enrich its publications with OpenAlex citation
 * metrics (matched by DOI first, then title). Missing or empty sources yield
 * no publications and no metrics.
 */
function loadPublicationsWithMetrics(
  source: string | undefined,
  locale?: string
): { publications: Publication[]; metrics: OpenAlexMetrics | null } {
  if (!source) {
    return { publications: [], metrics: null };
  }

  const bibtex = getBibtexContent(source, locale);
  const metrics = getCitationMetrics();
  const publications = parseBibTeX(bibtex, locale).map((publication) => {
    const workMetrics = getMetricsForPublication(publication, metrics);
    if (!workMetrics) return publication;
    return { ...publication, citations: workMetrics.citations, openalexId: workMetrics.openalexId };
  });

  return { publications, metrics };
}

function loadDynamicPageData(slug: string, locale?: string): DynamicPageLocaleData | null {
  const pageConfig = getPageConfig(slug, locale) as BasePageConfig | null;

  if (!pageConfig) {
    return null;
  }

  if (pageConfig.type === 'publication') {
    const pubConfig = pageConfig as PublicationPageConfig;
    const { publications, metrics } = loadPublicationsWithMetrics(pubConfig.source, locale);
    return {
      type: 'publication',
      config: pubConfig,
      publications,
      metrics: toMetricsSummary(metrics),
    };
  }

  if (pageConfig.type === 'cv') {
    // Merge any localized override (title/description/headings) over the
    // default CV data; omitted sections fall back to the default file.
    const defaultCv = getPageConfig<CvPageConfig>(slug) as CvPageConfig;
    const localizedCv = locale ? (getPageConfig<CvPageConfig>(slug, locale) as CvPageConfig | null) : null;
    const cvConfig = mergeCvData(defaultCv, localizedCv);

    // Reuse the existing BibTeX pipeline for the publications section.
    const { publications } = loadPublicationsWithMetrics(cvConfig.publications?.source, locale);

    return {
      type: 'cv',
      config: cvConfig,
      publications,
    };
  }

  if (pageConfig.type === 'text') {
    const textConfig = pageConfig as TextPageConfig;
    const content = getMarkdownContent(textConfig.source, locale);
    return {
      type: 'text',
      config: textConfig,
      content,
    };
  }

  if (pageConfig.type === 'card') {
    return {
      type: 'card',
      config: pageConfig as CardPageConfig,
    };
  }

  return null;
}

export function generateStaticParams() {
  const config = getConfig();

  // Pages linked from the main navigation (except the homepage, which lives
  // at "/" and is generated by src/app/page.tsx).
  const navSlugs = config.navigation
    .filter((nav) => nav.type === 'page' && nav.target !== 'about')
    .map((nav) => nav.target);

  // Additional pages not shown in the main nav menu ([[subpages]]).
  const subpageSlugs = (config.subpages || []).map((page) => page.target);

  // Legal pages linked from the footer ([legal] section).
  const legalSlugs = [config.legal?.imprint, config.legal?.privacy].filter(
    (slug): slug is string => Boolean(slug)
  );

  const slugs = Array.from(new Set([...navSlugs, ...subpageSlugs, ...legalSlugs]));

  return slugs.map((slug) => ({
    slug,
  }));
}

export async function generateMetadata({ params }: { params: Promise<{ slug: string }> }): Promise<Metadata> {
  const { slug } = await params;
  const pageConfig = getPageConfig(slug) as BasePageConfig | null;

  if (!pageConfig) {
    return {};
  }

  return {
    // An empty title ("") hides the on-page heading; fall back to the bare site
    // title for the tab (absolute bypasses the "%s | ..." template).
    title: pageConfig.title || { absolute: getConfig().site.title },
    description: pageConfig.description,
  };
}

export default async function DynamicPage({ params }: { params: Promise<{ slug: string }> }) {
  const { slug } = await params;

  const baseConfig = getConfig();
  const runtimeI18n = getRuntimeI18nConfig(baseConfig.i18n);
  const targetLocales = runtimeI18n.enabled ? runtimeI18n.locales : [runtimeI18n.defaultLocale];

  const dataByLocale: Record<string, DynamicPageLocaleData> = {};

  for (const locale of targetLocales) {
    const localizedData = loadDynamicPageData(slug, locale);
    if (localizedData) {
      dataByLocale[locale] = localizedData;
    }
  }

  const defaultData = loadDynamicPageData(slug);
  if (defaultData) {
    dataByLocale[runtimeI18n.defaultLocale] = dataByLocale[runtimeI18n.defaultLocale] || defaultData;
  }

  if (Object.keys(dataByLocale).length === 0) {
    notFound();
  }

  return <DynamicPageClient dataByLocale={dataByLocale} defaultLocale={runtimeI18n.defaultLocale} />;
}
